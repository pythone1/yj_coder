import pandas as pd

# 读取 Excel 文件
df = pd.read_excel(r'E:\全省养殖池溏上图入库普查\养殖信息统计\20250709\4月9日丹阳市除虾蟹外5亩以上养殖主体（按照图斑统计）.xlsx')  # ← 替换为你的实际路径

# 定义主体标识列
主体字段 = ['镇', '村', '养殖经营人名称', '身份证号', '联系方式']

# 去重后统计每个镇的主体数量
主体去重 = df.drop_duplicates(subset=主体字段)
主体统计 = 主体去重.groupby('镇').size().reset_index(name='养殖主体数量')

# 重命名列，便于输出
主体统计 = 主体统计.rename(columns={'镇': '镇名称'})

# 保存结果
主体统计.to_excel(r'E:\全省养殖池溏上图入库普查\养殖信息统计\20250709\4月9日丹阳市除虾蟹外5亩以上养殖主体数量按镇统计.xlsx', index=False)

print("✅ 已保存：各镇养殖主体统计.xlsx")
