def clear_paragraph(paragraph):
    p = paragraph._element
    for child in list(p):
        if child.tag != qn("w:pPr"):
            p.remove(child)


def add_colored_text(paragraph, text, size=11, bold=False):
    run = paragraph.add_run(text)
    run.font.name = "宋体"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = RGBColor(0x00, 0x66, 0xCC)


def revise():
    shutil.copyfile(SRC_PATH, OUT_PATH)
    doc = Document(OUT_PATH)
    for idx, text in REVISIONS.items():
        p = doc.paragraphs[idx - 1]
        style_name = p.style.name if p.style else ""
        clear_paragraph(p)
        if "标题" in style_name or "Heading" in style_name:
            add_colored_text(p, text, size=12 if "四级" not in style_name else 11, bold=True)
        else:
            add_colored_text(p, text, size=11, bold=False)
    doc.save(OUT_PATH)
    print(OUT_PATH)


if __name__ == "__main__":
    revise()
