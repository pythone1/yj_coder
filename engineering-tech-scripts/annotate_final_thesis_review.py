def insert_paragraph_after(paragraph, text):
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    from docx.text.paragraph import Paragraph
    return Paragraph(new_p, paragraph._parent)


def set_run_font(run, size=10.5, color=None, bold=False):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = color


def add_note_after(paragraph, text):
    note_p = insert_paragraph_after(paragraph, "")
    note_p.style = paragraph.style
    run = note_p.add_run(text)
    set_run_font(run, size=10.5, color=RGBColor(0xC0, 0x00, 0x00), bold=False)
    try:
        run.font.highlight_color = WD_COLOR_INDEX.YELLOW
    except Exception:
        pass
    return note_p


