def set_font(run, size=12, bold=False):
    run.font.name = "宋体"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    run.font.size = Pt(size)
    run.bold = bold


def add_paragraph(doc, text="", size=12, bold=False, align=None):
    p = doc.add_paragraph()
    if text:
        run = p.add_run(text)
        set_font(run, size=size, bold=bold)
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(4)
    return p


def add_bullets(doc, items):
    for item in items:
        p = doc.add_paragraph(style="List Bullet")
        run = p.add_run(item)
        set_font(run, size=11)
        p.paragraph_format.space_after = Pt(2)


def add_title(doc, title, subtitle):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(title)
    set_font(r, size=18, bold=True)
    p2 = doc.add_paragraph()
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r2 = p2.add_run(subtitle)
    set_font(r2, size=11)


def add_question(doc, label, source, stem, analysis, answer=None):
    add_paragraph(doc, f"{label}", size=12, bold=True)
    add_paragraph(doc, f"来源：{source}", size=10)
    add_paragraph(doc, f"题目：{stem}", size=11)
    if answer:
        add_paragraph(doc, f"答案：{answer}", size=11, bold=True)
    add_paragraph(doc, "解析：", size=11, bold=True)
    for part in analysis:
        add_paragraph(doc, part, size=11)


