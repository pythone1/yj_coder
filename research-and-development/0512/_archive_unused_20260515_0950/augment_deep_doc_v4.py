p(doc, "对外演讲中，1.3“供水管网AI模型应用的发展”可以进一步展开为一条技术演进线。第一阶段是符号智能，依靠专家规则和逻辑推理，适合表达“如果压力低于阈值则报警”这类明确规则。第二阶段是统计学习，依靠历史样本学习分类、回归和聚类规律，典型方法包括线性回归、支持向量机、决策树和聚类算法。第三阶段是深度学习，神经网络可以处理更复杂的非线性关系，LSTM、GRU、CNN、自编码器等模型让高频流量、压力、声学和多源传感数据具备更强的建模空间。")
p(doc, "水务行业的AI应用并不需要一开始就追求最前沿模型。更合理的理解是：符号规则解决明确边界，统计模型解决稳定规律，深度学习解决复杂时序和多变量耦合，大模型智能体解决跨系统解释和协同。把这些能力放在同一张技术路线图上，听众会更容易理解为什么DMA漏损检测不是“换一个算法”，而是从经验阈值向数据模型和业务闭环升级。")

h(doc, "9.2 从通用AI到水务AI的迁移逻辑", 2)
p(doc, "通用AI进入水务行业时，必须经过场景约束。水务数据具有强物理约束、强时序特征、强空间拓扑和强运维流程属性。流量和压力不是普通数值，它们受水力边界、泵阀状态、用户需水、管网拓扑、地形高差和压力制度共同影响。因此，水务AI不能只套用通用算法模板，而要把机理知识、数据质量和业务流程纳入模型设计。")
p(doc, "以LSTM为例，通用时间序列预测只关心预测误差，但DMA漏损预测还要关心残差是否出现在MNF窗口、是否持续、是否与压力点同步、是否受节假日和合法夜间用水影响。以GNN为例，普通图模型只关心节点和边的连接，但供水管网图还要考虑流向、管径、阻力、阀门状态和压力传播。这样的解释可以帮助听众理解“为什么水务AI需要懂水务”。")

h(doc, "十、补充扩展：DMA指标体系与管理口径", 1)
h(doc, "10.1 NRW、漏损率与MNF的关系", 2)
p(doc, "无收益水量（NRW）通常包括物理漏损、计量误差、未授权用水和账务管理损失。漏损率是结果性指标，反映供水企业总体漏损控制水平；MNF是过程性指标，更适合用于DMA日常诊断。对外演讲时应避免把这些指标混为一谈。NRW偏经营统计，漏损率偏管理考核，MNF偏运行监测，AI模型则连接运行监测和管理决策。")
p(doc, "MNF的价值在于高频、敏感、可复盘。若某DMA夜间最小流量连续抬升，且无明显合法用水解释，就应进入异常观察；若维修后MNF明显回落，则可作为处置效果的辅助证据。但MNF不能单独证明漏损，因为它还受到边界连通、仪表误差、压力变化和夜间用户行为影响。")

h(doc, "10.2 DMA健康度指标", 2)
p(doc, "DMA健康度可以从四类指标构建。第一类是水量指标，包括日总量、MNF、夜间底流、单位用户夜间流量、供售差趋势。第二类是压力指标，包括平均压力、末梢压力、压力波动、低压时长、高压时长。第三类是资产指标，包括管龄、材质、维修频次、爆管记录、阀门可靠性。第四类是业务指标，包括投诉、工单响应时间、维修闭环时间、误报率和复盘率。")
p(doc, "AI模型可以把这些指标转化为DMA风险画像。比如某DMA日总量正常但MNF持续抬升，可能是背景漏损增加；某DMA流量突增且末梢压力下降，可能是突发漏损；某DMA频繁报警但现场无漏点，可能是边界或仪表问题；某DMA资产风险高但当前曲线正常，适合进入预防性巡检或改造计划。")

h(doc, "十一、补充扩展：模型工程细节", 1)
h(doc, "11.1 时间窗口与特征构造", 2)
p(doc, "时序模型的效果很大程度取决于时间窗口。短窗口如过去3小时到24小时，适合识别突发漏损和短期压力波动；中窗口如过去7天到30天，适合学习周周期和工作日/周末差异；长窗口如过去3个月到1年，适合学习季节性和长期趋势。工程上可同时构造短期、中期和长期特征，交给模型判断不同尺度的异常。")
p(doc, "常用特征包括：当前值、滑动均值、滑动标准差、同比同环比、夜间窗口最小值、残差累计值、压力-流量比、压力下降持续时长、节假日标记、降雨温度、阀门操作标记和设备维护标记。对漏损而言，单点突刺不一定重要，持续性、方向性和多变量一致性更重要。")

h(doc, "11.2 标签体系设计", 2)
p(doc, "标签体系是从无监督走向监督学习的关键。建议至少设置一级标签和二级标签。一级标签包括真实漏损、误报、设备故障、边界异常、合法用水、施工扰动、未知原因。二级标签可进一步细分为暗漏、明漏、爆管、二供补水、消防用水、商业夜间用水、流量计漂移、压力计故障、阀门误开误关等。")
p(doc, "标签应记录发生时间、发现时间、修复时间、位置、管段编号、DMA编号、漏损类型、处置方式和维修后效果。若只有“某路漏水”这样的自然语言工单，模型很难学习。工单系统应尽量结构化，让现场人员用选择项和地图点位完成反馈。")

h(doc, "11.3 模型评估口径", 2)
p(doc, "模型评估不能只用准确率。漏损检测中，漏报代价和误报代价不同。漏报可能导致漏损扩大和爆管，误报会增加巡检成本和人员疲劳。应同时评估召回率、精确率、F1、误报工单比例、提前预警时间、平均定位范围、TopN命中率和维修后MNF回落情况。")
p(doc, "事件级评估比点级评估更贴近业务。点级评估关注每个时间点是否判断正确，事件级评估关注一次漏损事件是否被提前发现、是否持续跟踪、是否正确派单、是否形成复盘。对外演讲中可以说：算法指标证明模型能力，业务指标证明系统价值。")

h(doc, "十二、补充扩展：典型算法讲解话术", 1)
h(doc, "12.1 LSTM/GRU讲解话术", 2)
p(doc, "可以这样讲：供水曲线不是随机波动，它有自己的生活节奏。早晚高峰、夜间低谷、工作日和周末、夏季和冬季都有规律。LSTM/GRU的作用就是学习这个节奏，预测在正常情况下某个DMA此时应该有多少流量、多少压力。当实际曲线持续偏离模型预测，并且偏离方向符合漏损特征时，系统就会提示人工复核。")

h(doc, "12.2 孤立森林和DBSCAN讲解话术", 2)
p(doc, "可以这样讲：很多漏损没有完整标签，所以我们不能一开始就要求模型知道所有漏损长什么样。孤立森林和DBSCAN更像是巡检助手，它们先学习大多数正常运行状态，再把少数不一样的时段找出来。它们不能直接证明漏损，但可以把人工需要查看的范围大幅缩小。")

h(doc, "12.3 自编码器讲解话术", 2)
p(doc, "可以这样讲：自编码器先学习正常状态下多个传感器之间的组合关系。正常情况下，流量、压力、阀门和用水模式之间有相对稳定的配合。当某种异常出现时，这种配合关系被打破，模型就难以还原原始信号，重构误差变大。这个误差就是异常信号。")

h(doc, "12.4 随机森林/GBDT讲解话术", 2)
p(doc, "可以这样讲：树模型适合把老师傅经验结构化。哪些管材容易漏，哪些管龄进入高风险期，哪些道路施工多，哪些区域压力波动大，哪些管段维修频次高，这些因素可以一起进入模型，输出管段风险排序。这样巡检和改造就不再只靠经验，而是有数据支撑。")

h(doc, "12.5 GNN讲解话术", 2)
p(doc, "可以这样讲：供水管网本身就是一张图。漏点发生后，不只影响一个传感器，而会沿管道拓扑改变多个压力点的响应。GNN的目标是学习这种图上的传播关系。但它对拓扑和传感器质量要求更高，所以更适合放在第二阶段或重点DMA深化应用。")

