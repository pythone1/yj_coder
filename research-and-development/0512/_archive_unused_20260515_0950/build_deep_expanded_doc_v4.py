RED = RGBColor(192, 0, 0)
BLACK = RGBColor(0, 0, 0)
BLUE_FILL = "D9EAF7"


def set_run(run, red=True, bold=False, size=10.5, font="宋体"):
    run.font.name = font
    run._element.rPr.rFonts.set(qn("w:eastAsia"), font)
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = RED if red else BLACK


def shade(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def setup(doc):
    sec = doc.sections[0]
    sec.top_margin = Inches(0.72)
    sec.bottom_margin = Inches(0.72)
    sec.left_margin = Inches(0.78)
    sec.right_margin = Inches(0.78)
    for name in ["Normal", "List Bullet", "List Number"]:
        st = doc.styles[name]
        st.font.name = "宋体"
        st._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
        st.font.size = Pt(10.5)
    for name in ["Heading 1", "Heading 2", "Heading 3", "Heading 4"]:
        st = doc.styles[name]
        st.font.name = "黑体"
        st._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")
        st.font.color.rgb = BLACK


def title(doc, text, sub):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    set_run(r, False, True, 22, "黑体")
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(sub)
    set_run(r, True, False, 11)
    doc.add_paragraph()


def h(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        set_run(r, False, True, 16 if level == 1 else 13 if level == 2 else 11.5 if level == 3 else 10.5, "黑体")


def p(doc, text, red=True):
    para = doc.add_paragraph()
    para.paragraph_format.first_line_indent = Pt(21)
    para.paragraph_format.line_spacing = 1.25
    r = para.add_run(text)
    set_run(r, red, False, 10.5)
    return para


def bullet(doc, text, red=True):
    para = doc.add_paragraph(style="List Bullet")
    para.paragraph_format.line_spacing = 1.15
    r = para.add_run(text)
    set_run(r, red)


def table(doc, headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.style = "Table Grid"
    for i, head in enumerate(headers):
        c = t.rows[0].cells[i]
        shade(c, BLUE_FILL)
        c.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        pp = c.paragraphs[0]
        pp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = pp.add_run(head)
        set_run(r, False, True, 9.2, "黑体")
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            pp = cells[i].paragraphs[0]
            pp.paragraph_format.line_spacing = 1.05
            r = pp.add_run(val)
            set_run(r, True, False, 8.8)
    doc.add_paragraph()


