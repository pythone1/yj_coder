def clear_paragraph(paragraph):
    p = paragraph._element
    for child in list(p):
        if child.tag != qn("w:pPr"):
            p.remove(child)


def add_text(paragraph, text, color="C00000", bold=False):
    run = paragraph.add_run(text)
    run.font.name = "宋体"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    run.font.size = Pt(11)
    run.bold = bold
    rgb = RGBColor.from_string(color)
    run.font.color.rgb = rgb


def main():
    shutil.copyfile(SRC_PATH, OUT_PATH)
    doc = Document(OUT_PATH)
    for idx, text in REVISIONS.items():
        p = doc.paragraphs[idx - 1]
        style_name = p.style.name if p.style else ""
        clear_paragraph(p)
        is_heading = ("标题" in style_name) or ("Heading" in style_name)
        add_text(p, text, color="C00000", bold=is_heading)
    doc.save(OUT_PATH)
    print(OUT_PATH)


if __name__ == "__main__":
    main()
